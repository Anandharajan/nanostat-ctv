"""Minimal four-pillar audit bundle (SPEC §10).

ZIP contents: protocol.json, audit_events.jsonl (hash-chained), analysis.py (standalone,
generated from a fixed per-method template), data.csv, result.json, admissible_range.csv,
parity.json, assumptions_report.json, README.md, manifest.sha256.
"""

from __future__ import annotations

import csv
import hashlib
import io
import json
import zipfile
from pathlib import Path
from typing import Any

from nanostat import __version__
from nanostat.controller import RunRecord
from nanostat.parity.r_backend import parity_check

# --- standalone analysis templates (scipy + pandas only) ---------------------------------

_HEADER = '''"""Re-run the primary analysis from this bundle. Requires: python>=3.10, numpy, pandas, scipy.
Generated by NanoStat-CTV {version}. Usage: python analysis.py  (prints result JSON)"""
import json
import numpy as np
import pandas as pd
from scipy import stats

PLAN = json.loads(open("protocol.json", encoding="utf-8").read())["plan"]
STUDY = json.loads(open("protocol.json", encoding="utf-8").read())["study"]
C = PLAN["columns"]
ALT = PLAN.get("alternative", "two-sided")
df = pd.read_csv("data.csv")
'''

_PREPROCESS = """
if PLAN.get("preprocess"):
    # Preprocessing uses the typed DSL; re-run it with the same package version.
    from nanostat.dsl import apply_preprocess
    from nanostat.schemas import Plan
    df, _log, _changed = apply_preprocess(df, Plan.model_validate(PLAN))
"""

_EXTRACT = {
    "two": """
order = STUDY.get("group_order") or sorted(df[C["group"]].dropna().astype(str).unique())
g = df[C["group"]].astype(str)
a = pd.to_numeric(df.loc[g == order[1], C["y"]]).dropna().to_numpy(float)
b = pd.to_numeric(df.loc[g == order[0], C["y"]]).dropna().to_numpy(float)
""",
    "paired": """
if "y1" in C:
    sub = df[[C["y1"], C["y2"]]].apply(pd.to_numeric, errors="coerce").dropna()
    y2, y1 = sub[C["y2"]].to_numpy(float), sub[C["y1"]].to_numpy(float)
else:
    order = STUDY.get("group_order") or sorted(df[C["group"]].dropna().astype(str).unique())
    t = df[[C["pair_id"], C["group"], C["y"]]].copy()
    t[C["group"]] = t[C["group"]].astype(str)
    w = t.pivot(index=C["pair_id"], columns=C["group"], values=C["y"])[order].dropna()
    y2, y1 = w[order[1]].to_numpy(float), w[order[0]].to_numpy(float)
""",
    "xy": """
sub = df[[C["x"], C["y"]]].apply(pd.to_numeric, errors="coerce").dropna()
x, y = sub[C["x"]].to_numpy(float), sub[C["y"]].to_numpy(float)
""",
    "k": """
levels = sorted(df[C["group"]].dropna().astype(str).unique())
if STUDY.get("group_order"):
    levels = STUDY["group_order"] + [v for v in levels if v not in STUDY["group_order"]]
g = df[C["group"]].astype(str)
gs = [pd.to_numeric(df.loc[g == lv, C["y"]]).dropna().to_numpy(float) for lv in levels]
""",
    "table": """
order = STUDY.get("group_order") or sorted(df[C["group"]].dropna().astype(str).unique())
sub = df[[C["y"], C["group"]]].dropna()
yv = pd.to_numeric(sub[C["y"]], errors="coerce")
if yv.notna().all():
    yy = yv.to_numpy(float).astype(int)
else:
    lv = sorted(sub[C["y"]].astype(str).unique()); yy = (sub[C["y"]].astype(str) == lv[1]).to_numpy().astype(int)
gs_ = sub[C["group"]].astype(str).to_numpy()
table = np.array([[((gs_ == order[1]) & (yy == 1)).sum(), ((gs_ == order[1]) & (yy == 0)).sum()],
                  [((gs_ == order[0]) & (yy == 1)).sum(), ((gs_ == order[0]) & (yy == 0)).sum()]])
""",
    "one": """
s = df[C["y"]].dropna()
yv = pd.to_numeric(s, errors="coerce")
yy = yv.to_numpy(float).astype(int) if yv.notna().all() else (s.astype(str) == sorted(s.astype(str).unique())[1]).to_numpy().astype(int)
p0 = PLAN.get("params", {}).get("p0", STUDY.get("p0"))
""",
}

_CALL = {
    "welch_t": ("two", "r = stats.ttest_ind(a, b, equal_var=False, alternative=ALT)"),
    "student_t": ("two", "r = stats.ttest_ind(a, b, equal_var=True, alternative=ALT)"),
    "yuen_trimmed_t": ("two", "r = stats.ttest_ind(a, b, equal_var=False, trim=0.2, alternative=ALT)"),
    "mann_whitney": ("two", "r = stats.mannwhitneyu(a, b, alternative=ALT, method='auto')"),
    "paired_t": ("paired", "r = stats.ttest_rel(y2, y1, alternative=ALT)"),
    "wilcoxon_signed_rank": (
        "paired",
        "r = stats.wilcoxon(y2 - y1, alternative=ALT, zero_method='wilcox', method='auto')",
    ),
    "pearson": ("xy", "r = stats.pearsonr(x, y, alternative=ALT)"),
    "spearman": ("xy", "r = stats.spearmanr(x, y, alternative=ALT)"),
    "anova_oneway": ("k", "r = stats.f_oneway(*gs)"),
    "kruskal_wallis": ("k", "r = stats.kruskal(*gs)"),
    "chi2_independence": ("table", "r = stats.chi2_contingency(table, correction=False)"),
    "fisher_exact": ("table", "r = stats.fisher_exact(table, alternative=ALT)"),
    "binomial_test": ("one", "r = stats.binomtest(int(yy.sum()), len(yy), p0, alternative=ALT)"),
}

_FOOTER = """
print(json.dumps({"method": PLAN["method"], "p_value": float(r.pvalue)}))
"""


def analysis_script(method: str) -> str:
    kind, call = _CALL[method]
    return _HEADER.format(version=__version__) + _PREPROCESS + _EXTRACT[kind] + call + "\n" + _FOOTER


def _sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def build_bundle(rec: RunRecord, data_csv: bytes, out: Path) -> Path:
    files: dict[str, bytes] = {}
    plan = rec.plan.model_dump(mode="json") if rec.plan else None
    protocol: dict[str, Any] = {
        "nanostat_version": __version__,
        "question": rec.question,
        "study": rec.study.model_dump(mode="json"),
        "plan": plan,
        "planner_attempts": rec.attempts,
        "data_sha256": _sha(data_csv),
        "policy_cell": rec.result.policy_cell,
    }
    files["protocol.json"] = json.dumps(protocol, indent=2).encode()
    files["audit_events.jsonl"] = rec.audit.to_jsonl().encode()
    files["data.csv"] = data_csv
    files["result.json"] = rec.result.model_dump_json(indent=2).encode()

    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(["method", "statistic", "p", "effect", "error"])
    for row in rec.result.admissible_range:
        w.writerow([row.method, row.statistic, row.p, row.effect, row.error or ""])
    files["admissible_range.csv"] = buf.getvalue().encode()

    files["assumptions_report.json"] = json.dumps(rec.result.diagnostics, indent=2, default=str).encode()
    files["parity.json"] = json.dumps(parity_check(rec, data_csv), indent=2).encode()

    rerun = "python analysis.py"
    if rec.plan is not None and rec.plan.method in _CALL and rec.result.p_value is not None:
        files["analysis.py"] = analysis_script(rec.plan.method).encode()
    else:
        rerun = "(no executed analysis in this run)"
    files["README.md"] = (
        "# NanoStat-CTV audit bundle\n\n"
        f"Question: {rec.question}\n\n"
        f"Action: {rec.result.action.value}; method: {rec.result.method}; "
        f"p = {rec.result.p_value}; decision: {rec.result.decision}; "
        f"method status: {rec.result.method_status.value}\n\n"
        "## Re-run\n\n"
        f"```\npip install numpy pandas scipy\n{rerun}\n```\n\n"
        "Compare the printed p_value with result.json. `admissible_range.csv` lists every "
        "admissible method for the inferred design cell, run on the same data. "
        "`audit_events.jsonl` is hash-chained; `manifest.sha256` covers every file.\n"
    ).encode()

    manifest = "".join(f"{_sha(b)}  {name}\n" for name, b in sorted(files.items()))
    files["manifest.sha256"] = manifest.encode()

    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED) as z:
        for name in sorted(files):
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(info, files[name])
    return out


def verify_manifest(zip_path: Path) -> bool:
    with zipfile.ZipFile(zip_path) as z:
        lines = z.read("manifest.sha256").decode().splitlines()
        for line in lines:
            h, name = line.split("  ", 1)
            if _sha(z.read(name)) != h:
                return False
    return True
