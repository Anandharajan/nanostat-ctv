"""LLM-assisted PRE-review of the admissible-set policy registry (local model, e.g. via Magnitude).

This is NOT the statistician sign-off required by SPEC §6.2. It produces a worksheet that a human
statistician can use: for every cell the local model is asked to AGREE / DISAGREE with each
admissible and invalid label and to name missing methods. The registry's `reviewed_by` field is never
changed by this module; it stays PENDING until a named person signs.
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from nanostat.policy import PolicyCell, load_policies

PROMPT = """You are an experienced applied statistician reviewing a rule table used by an automated
hypothesis-testing assistant. Be critical and concise.

Situation: design = {design}; outcome = {outcome}; detected data issue = {perturbation}.
Methods the table calls ADMISSIBLE, by estimand: {admissible}
Methods the table calls INVALID, with reasons: {invalid}

Reply with JSON only:
{{"admissible": [{{"method": str, "verdict": "AGREE"|"DISAGREE", "reason": str}}],
  "invalid": [{{"method": str, "verdict": "AGREE"|"DISAGREE", "reason": str}}],
  "missing_methods": [str], "overall": "OK"|"NEEDS_CHANGES", "comment": str}}
"""


@dataclass
class CellReview:
    cell: str
    raw: str
    parsed: dict | None


def prompt_for(cell: PolicyCell) -> str:
    return PROMPT.format(
        design=cell.design.value,
        outcome=cell.outcome.value,
        perturbation=cell.perturbation,
        admissible=json.dumps(cell.estimand_options),
        invalid=json.dumps(cell.invalid),
    )


def _parse(text: str) -> dict | None:
    m = re.search(r"\{.*\}", text, re.S)
    if not m:
        return None
    try:
        return json.loads(m.group(0))
    except json.JSONDecodeError:
        return None


def run_review(generate: Callable[[str], str]) -> list[CellReview]:
    out = []
    for key, cell in sorted(load_policies().items()):
        raw = generate(prompt_for(cell))
        out.append(CellReview(key, raw, _parse(raw)))
    return out


def write_worksheet(reviews: list[CellReview], model: str, path: Path) -> None:
    lines = [
        "# Policy registry pre-review worksheet",
        "",
        f"**Generated by a local LLM ({model}). This is NOT a statistician sign-off.** Every cell keeps "
        "`reviewed_by: PENDING` until a named statistician reviews it. Use the disagreements below as a "
        "starting checklist for that review.",
        "",
        "| Cell | Model's overall | Disagreements | Missing methods suggested |",
        "|---|---|---|---|",
    ]
    for r in reviews:
        if r.parsed is None:
            lines.append(f"| {r.cell} | (unparseable reply) | — | — |")
            continue
        dis = [
            f"{x.get('method')}: {x.get('reason', '')}"
            for k in ("admissible", "invalid")
            for x in r.parsed.get(k, [])
            if str(x.get("verdict", "")).upper() == "DISAGREE"
        ]
        miss = ", ".join(map(str, r.parsed.get("missing_methods", []))) or "—"
        lines.append(f"| {r.cell} | {r.parsed.get('overall', '?')} | {'; '.join(dis) or '—'} | {miss} |")
    lines += ["", "## Raw replies", ""]
    for r in reviews:
        lines += [f"### {r.cell}", "", "```", r.raw.strip(), "```", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
